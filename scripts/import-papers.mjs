import fs from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const sourceDir = path.join(projectRoot, "data", "papers");
const outputFile = path.join(projectRoot, "src", "data", "papers.imported.ts");

function toJson(value) {
  return JSON.stringify(value, null, 2);
}

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function isPaperFile(name) {
  return name.endsWith(".json") && !name.startsWith("_");
}

function validatePaperShape(fileName, paper) {
  const requiredTopLevel = ["paper", "passages"];
  for (const key of requiredTopLevel) {
    if (!(key in paper)) {
      throw new Error(`[${fileName}] missing key: ${key}`);
    }
  }

  const requiredPaperFields = ["id", "exam", "year", "month", "set", "title"];
  for (const key of requiredPaperFields) {
    if (!(key in paper.paper)) {
      throw new Error(`[${fileName}] missing paper.${key}`);
    }
  }

  if (!Array.isArray(paper.passages) || paper.passages.length === 0) {
    throw new Error(`[${fileName}] passages must be a non-empty array`);
  }

  for (const [index, passage] of paper.passages.entries()) {
    const requiredPassageFields = ["id", "section", "title", "content"];
    for (const key of requiredPassageFields) {
      if (!(key in passage)) {
        throw new Error(`[${fileName}] passages[${index}] missing ${key}`);
      }
    }
    if (!Array.isArray(passage.highlightSeeds)) {
      throw new Error(`[${fileName}] passages[${index}].highlightSeeds must be an array`);
    }
  }
}

function normalizeToArticleSeed(input) {
  const p = input.paper;
  return input.passages.map((passage) => ({
    id: passage.id,
    exam: p.exam,
    year: p.year,
    month: p.month,
    set: p.set,
    paperId: p.id,
    section: passage.section,
    title: passage.title,
    level: passage.level || "CET-6",
    category: passage.category || "Exam Reading",
    modeLabel: passage.modeLabel || "阅读学习模式",
    content: passage.content,
    highlightSeeds: passage.highlightSeeds || []
  }));
}

function normalizeToPaper(input) {
  const p = input.paper;
  return {
    id: p.id,
    exam: p.exam,
    year: p.year,
    month: p.month,
    set: p.set,
    title: p.title,
    passageIds: input.passages.map((item) => item.id)
  };
}

function main() {
  ensureDir(sourceDir);
  ensureDir(path.dirname(outputFile));

  const files = fs.readdirSync(sourceDir).filter(isPaperFile).sort();
  const allArticleSeeds = [];
  const allPapers = [];

  for (const fileName of files) {
    const fullPath = path.join(sourceDir, fileName);
    const raw = fs.readFileSync(fullPath, "utf8");
    const data = JSON.parse(raw);
    validatePaperShape(fileName, data);
    allArticleSeeds.push(...normalizeToArticleSeed(data));
    allPapers.push(normalizeToPaper(data));
  }

  const output = `/* eslint-disable */
/* Auto-generated by scripts/import-papers.mjs. Do not edit directly. */
import { Article, ExamPaper } from "@/types";

type ImportedHighlightSeed = {
  id: string;
  word: string;
  sentence: string;
  ipa?: string;
  partOfSpeech?: string;
};

export type ImportedArticleSeed = Omit<Article, "highlights" | "practice"> & {
  highlightSeeds: ImportedHighlightSeed[];
};

export const importedArticleSeeds: ImportedArticleSeed[] = ${toJson(allArticleSeeds)};

export const importedExamPapers: ExamPaper[] = ${toJson(allPapers)};
`;

  fs.writeFileSync(outputFile, output, "utf8");
  console.log(
    `[import:papers] generated ${path.relative(projectRoot, outputFile)} | papers=${allPapers.length} passages=${allArticleSeeds.length}`
  );
}

main();

